#!/bin/bash
# Copy the ports' fakes listed in fake/ports/FILES from git checkouts into
# fake/ports/<port>/, and record where each came from in fake/ports/MANIFEST
# (file, sha256, repository, commit, path there).
#
#   fake/ports/sync.sh CHECKOUTS      e.g. fake/ports/sync.sh ~/src
#
# CHECKOUTS holds a checkout of each repository named in FILES
# (riscos-mesa, riscos-unixlib, ...), normally at its latest commit on
# github.com/adyoull. The files are copied unchanged: fix a fake in its
# port, then sync it here. fake/ports/check.sh tells you if a copy here has
# been edited since.
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
SRC=${1:?usage: $0 CHECKOUTS}
OUT=$HERE/MANIFEST.new
{
  echo "# Generated by fake/ports/sync.sh: FILE SHA256 REPOSITORY COMMIT PATH"
  echo "# FILE is relative to fake/ports. Don't edit; change FILES and sync."
} > "$OUT"
# Start from nothing, so a file dropped from FILES goes too.
for d in "$HERE"/*/; do rm -rf "$d"; done
grep -v '^#' "$HERE/FILES" | while read -r port repo prefix path; do
  [ -n "$port" ] || continue
  r=$SRC/$repo
  [ -f "$r/$path" ] || { echo "missing: $r/$path" >&2; exit 1; }
  commit=$(git -C "$r" rev-parse --short HEAD)
  dest=$port/${path#"$prefix"}
  mkdir -p "$HERE/$(dirname "$dest")"
  cp -p "$r/$path" "$HERE/$dest"
  echo "$dest $(sha256sum < "$HERE/$dest" | cut -d' ' -f1) $repo $commit $path" >> "$OUT"
done
mv "$OUT" "$HERE/MANIFEST"
echo "$(grep -vc '^#' "$HERE/MANIFEST") files in fake/ports"
