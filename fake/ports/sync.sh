#!/bin/bash
# Copy the ports' fakes listed in fake/ports/FILES from git checkouts into
# fake/ports/<port>/, record where each came from in fake/fake_origin.md
# (file, repository, commit, path, sha256), then regenerate the shared SWI
# numbers (fake/swinames.h) from UnixLib's swis.h and the ports' copies.
#
#   fake/ports/sync.sh CHECKOUTS      e.g. fake/ports/sync.sh ~/src
#
# CHECKOUTS holds a checkout of each repository named in FILES
# (riscos-mesa, riscos-unixlib, ...), normally at its latest commit on
# github.com/adyoull. The files are copied unchanged: fix a fake in its
# port, then sync it here. fake/ports/check.sh tells you if a copy here has
# been edited since. Normally run through fake/ports/update.sh.
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
SRC=${1:?usage: $0 CHECKOUTS}
OWNER=${OWNER:-adyoull}
MD=$HERE/../fake_origin.md
ROWS=$(mktemp); trap 'rm -f "$ROWS"' EXIT
# Start from nothing, so a file dropped from FILES goes too.
for d in "$HERE"/*/; do rm -rf "$d"; done
grep -v '^#' "$HERE/FILES" | while read -r port repo prefix path; do
  [ -n "$port" ] || continue
  r=$SRC/$repo
  [ -f "$r/$path" ] || { echo "missing: $r/$path" >&2; exit 1; }
  commit=$(git -C "$r" rev-parse --short=7 HEAD)
  dest=$port/${path#"$prefix"}
  mkdir -p "$HERE/$(dirname "$dest")"
  cp -p "$r/$path" "$HERE/$dest"
  sum=$(sha256sum < "$HERE/$dest" | cut -d' ' -f1)
  u=https://github.com/$OWNER/$repo
  echo "| \`$dest\` | [$repo]($u) | [$commit]($u/tree/$commit) | [\`$path\`]($u/blob/$commit/$path) | \`$sum\` |" >> "$ROWS"
done
{
  cat <<'EOF'
# Where the fakes came from

Generated by `fake/ports/sync.sh` and `fake/gen-swinames.sh`; don't edit it.
`fake/ports/update.sh` takes the latest fakes from every port and writes it
again. `fake/ports/check.sh` (part of `make check`) reads the table below:
a copy that no longer matches its sha256 fails, because a fake is fixed in
the port it came from, never here.

## The ports' fakes, in `fake/ports/`

Copied unchanged from each port's repository at the commit shown. What
each one fakes is in `fake/ports/README.md`.

<!-- files -->
| File (in `fake/ports/`) | Repository | Commit | Path there | sha256 |
|---|---|---|---|---|
EOF
  cat "$ROWS"
  cat <<'EOF'
<!-- /files -->

## SWI numbers, in `fake/swinames.h`

<!-- swis -->
<!-- /swis -->
EOF
} > "$MD"
echo "$(grep -c '^| `' "$ROWS") files in fake/ports"
"$HERE/../gen-swinames.sh"
