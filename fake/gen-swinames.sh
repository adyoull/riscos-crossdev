#!/bin/bash
# Generate fake/swinames.h, the one set of SWI numbers for the Fake RISC OS:
# every SWI number in UnixLib's swis.h, plus any SWI the ports' own fakes
# define (their swis.h copies in fake/ports) that UnixLib doesn't have. It
# also writes the SWI section of fake/fake_origin.md: which port defines
# which SWIs, which ones the ports added, and any number that differs from
# UnixLib's (UnixLib's is kept; fake/ports/check-headers.sh reports it).
#
#   fake/gen-swinames.sh [SWIS_H]  (default: the toolchain's swis.h)
#   fake/gen-swinames.sh --check   (exit 1 if either is out of date)
#
# The toolchain's swis.h is riscos-unixlib's libunixlib/include/swis.h,
# installed by toolchain/build.sh. fake/ports/sync.sh runs this after
# taking the ports' fakes; run it yourself after a UnixLib update. It stops
# if two ports give a SWI that UnixLib doesn't have different numbers.
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
. "$HERE/../env.sh"
CHECK=0
[ "${1:-}" = --check ] && { CHECK=1; shift; }
SRC=${1:-$RISCOS_TOOLCHAIN/arm-riscos-gnueabihf/include/swis.h}
[ -f "$SRC" ] || { echo "no $SRC (install the toolchain, or name a swis.h)" >&2; exit 2; }
MD=$HERE/fake_origin.md
[ -f "$MD" ] || { echo "no $MD: run fake/ports/sync.sh" >&2; exit 2; }
UL=$(grep -o 'unixlib-riscos-[0-9.]*[0-9]\.diff' "$RISCOS_TOOLCHAIN/BUILDINFO.txt" 2>/dev/null | head -1 |
     sed 's/^unixlib-riscos-//; s/\.diff$//') || true
UL=${UL:+UnixLib $UL}
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT

# The ports' swis.h copies: FILE REPOSITORY, from fake_origin.md's table.
"$HERE/ports/origin.sh" "$MD" | awk '$1 ~ /(^|\/)swis\.h$/ {print $1, $3}' > "$TMP/ports"
args=()
while read -r f repo; do args+=("$HERE/ports/$f"); done < "$TMP/ports"

gawk -v H="$TMP/swinames.h" -v S="$TMP/section" -v PL="$TMP/ports" -v PD="$HERE/ports/" \
     -v UL="${UL:-UnixLib}" '
function swi(name) { return name ~ /^X?[A-Z][A-Za-z0-9]*_[A-Za-z0-9_]+$/ && name != "XOS_Bit" }
function hexval(t) { gsub(/[()]/, "", t); return (t ~ /^0[xX][0-9A-Fa-f]+$/) ? strtonum(t) : -1 }
BEGIN { while ((getline l < PL) > 0) { split(l, a, " "); repo[PD a[1]] = a[2] } }
FNR == 1 { file = FILENAME; first = (NR == 1) }
/^[ \t]*#[ \t]*define[ \t]/ {
  sub(/^[ \t]*#[ \t]*define[ \t]+/, ""); n = $1; v = hexval($2)
  if (v < 0 || !swi(n)) next
  if (first) { if (!(n in ul)) { ul[n] = v; uorder[++nu] = n } next }
  f = substr(file, length(PD) + 1)
  if (!(f in seenf)) { seenf[f] = 1; forder[++nf] = f }
  if (!((f, n) in def)) { def[f, n] = v; list[f] = list[f] (list[f] == "" ? "" : ", ") n; ndefs++ }
  if (!(n in anyport)) { anyport[n] = 1; nnames++ }
  if (n in ul) {
    if (ul[n] != v) bad[++nbad] = sprintf("| %s | 0x%x | `%s` (%s) | 0x%x |", n, ul[n], f, repo[file], v)
  } else if (n in extra) {
    if (extra[n] != v) { printf "ports disagree on %s: 0x%x in %s, 0x%x in %s (%s)\n", n, extra[n], by[n], v, f, repo[file] > "/dev/stderr"; err = 1 }
    else by[n] = by[n] ", `" f "` (" repo[file] ")"
  } else { extra[n] = v; by[n] = "`" f "` (" repo[file] ")"; eorder[++ne] = n }
}
END {
  if (err) exit 1
  print "/* Generated by fake/gen-swinames.sh: don'\''t edit, regenerate." > H
  print "   Every SWI number in UnixLib'\''s swis.h (riscos-unixlib," > H
  print "   libunixlib/include/swis.h, " UL "), then any SWI the ports'\'' own" > H
  print "   fakes define that UnixLib doesn'\''t (fake/fake_origin.md says which)." > H
  print "   Each is guarded, so a test can define its own first." > H
  print "   UnixLib'\''s numbers: Copyright (c) 2002-2006 UnixLib Developers;" > H
  print "   UnixLib'\''s licence. */" > H
  print "#ifndef FAKE_SWINAMES_H\n#define FAKE_SWINAMES_H" > H
  for (i = 1; i <= nu; i++) printf "#ifndef %s\n#define %-36s 0x%x\n#endif\n", uorder[i], uorder[i], ul[uorder[i]] > H
  if (ne) print "/* Not in UnixLib'\''s swis.h: from the ports'\'' fakes. */" > H
  for (i = 1; i <= ne; i++) printf "#ifndef %s\n#define %-36s 0x%x\n#endif\n", eorder[i], eorder[i], extra[eorder[i]] > H
  print "#endif" > H

  printf "Every SWI number in UnixLib'\''s `swis.h` (riscos-unixlib, %s, as installed in the toolchain): %d.\n\n", UL, nu > S
  printf "The ports'\'' `swis.h` copies define %d SWI numbers between them (%d different SWIs). ", ndefs, nnames > S
  if (!ne && !nbad) print "All of them are in UnixLib'\''s, with the same numbers." > S
  else printf "Not in UnixLib'\''s, so added: %d. With a different number from UnixLib'\''s: %d.\n", ne, nbad > S
  if (ne) {
    print "\n### SWIs the ports add\n\nNot in UnixLib'\''s `swis.h`, so `fake/swinames.h` takes them from the ports.\n" > S
    print "| SWI | Number | Defined by |\n|---|---|---|" > S
    for (i = 1; i <= ne; i++) printf "| %s | 0x%x | %s |\n", eorder[i], extra[eorder[i]], by[eorder[i]] > S
  }
  if (nbad) {
    print "\n### Numbers that differ from UnixLib'\''s\n\n`fake/swinames.h` keeps UnixLib'\''s. `fake/ports/check-headers.sh` reports these, for a handoff to the port.\n" > S
    print "| SWI | UnixLib | Port file | Port number |\n|---|---|---|---|" > S
    for (i = 1; i <= nbad; i++) print bad[i] > S
  }
  print "\n### The SWIs each port'\''s `swis.h` defines\n" > S
  print "| File (in `fake/ports/`) | Repository | SWIs |\n|---|---|---|" > S
  for (i = 1; i <= nf; i++) printf "| `%s` | %s | %s |\n", forder[i], repo[PD forder[i]], list[forder[i]] > S
}' "$SRC" "${args[@]}"

# Put the section into fake_origin.md between its markers.
awk -v S="$TMP/section" '
  /^<!-- \/swis -->/ { while ((getline l < S) > 0) print l; skip = 0 }
  !skip { print }
  /^<!-- swis -->/ { skip = 1 }' "$MD" > "$TMP/origin.md"

if [ $CHECK = 1 ]; then
  ok=1
  cmp -s "$TMP/swinames.h" "$HERE/swinames.h" || { echo "WRONG: fake/swinames.h is out of date: run fake/gen-swinames.sh" >&2; ok=0; }
  cmp -s "$TMP/origin.md" "$MD" || { echo "WRONG: fake/fake_origin.md's SWI section is out of date: run fake/gen-swinames.sh" >&2; ok=0; }
  [ $ok = 1 ] && echo "OK: fake/swinames.h and fake/fake_origin.md match $SRC and the ports' swis.h"
  [ $ok = 1 ]; exit
fi
mv "$TMP/swinames.h" "$HERE/swinames.h"
mv "$TMP/origin.md" "$MD"
echo "fake/swinames.h: $(grep -c '^#define [A-Za-z0-9_]* *0x' "$HERE/swinames.h") SWI numbers"
