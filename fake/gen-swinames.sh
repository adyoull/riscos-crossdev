#!/bin/bash
# Generate fake/swinames.h: every SWI number in UnixLib's swis.h, for the
# fake RISC OS, so host builds know every SWI name the real headers do.
#
#   fake/gen-swinames.sh [SWIS_H]  (default: the toolchain's swis.h)
#   fake/gen-swinames.sh --check   (exit 1 if fake/swinames.h is out of date)
#
# The toolchain's swis.h is riscos-unixlib's libunixlib/include/swis.h,
# installed by toolchain/build.sh. Regenerate after a UnixLib update.
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
. "$HERE/../env.sh"
CHECK=0
[ "${1:-}" = --check ] && { CHECK=1; shift; }
SRC=${1:-$RISCOS_TOOLCHAIN/arm-riscos-gnueabihf/include/swis.h}
[ -f "$SRC" ] || { echo "no $SRC (install the toolchain, or name a swis.h)" >&2; exit 2; }
OUT=$(mktemp)
{
  echo "/* Generated by fake/gen-swinames.sh from UnixLib's swis.h"
  echo "   (riscos-unixlib, libunixlib/include/swis.h; the toolchain installs it)."
  echo "   Every SWI number there, each guarded so that a test can define its own"
  echo "   first. Copyright (c) 2002-2006 UnixLib Developers; UnixLib's licence."
  echo "   Don't edit: regenerate. */"
  echo "#ifndef FAKE_SWINAMES_H"
  echo "#define FAKE_SWINAMES_H"
  grep -E '^#define[[:space:]]+[A-Za-z][A-Za-z0-9_]*[[:space:]]+0x[0-9A-Fa-f]+' "$SRC" |
    grep -v -E '^#define[[:space:]]+XOS_Bit[[:space:]]' |
    awk '{printf "#ifndef %s\n#define %-36s 0x%x\n#endif\n", $2, $2, strtonum($3)}'
  echo "#endif"
} > "$OUT"
if [ $CHECK = 1 ]; then
  if cmp -s "$OUT" "$HERE/swinames.h"; then echo "OK: fake/swinames.h matches $SRC"; rm -f "$OUT"; exit 0; fi
  echo "WRONG: fake/swinames.h is out of date: run fake/gen-swinames.sh" >&2; rm -f "$OUT"; exit 1
fi
mv "$OUT" "$HERE/swinames.h"
echo "fake/swinames.h: $(grep -c '^#define [A-Z]' "$HERE/swinames.h") SWI numbers"
